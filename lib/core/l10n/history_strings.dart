      ar ? 'إجمالي الحضور' : 'Total Present';

  static String whatsappTotalAbsent(bool ar) =>
      ar ? 'إجمالي الغياب' : 'Total Absent';

  static String whatsappWorkersLabel(bool ar) => ar ? 'العمال' : 'Workers';

  static String whatsappFooter(bool ar) =>
      ar ? '(تم الإنشاء بواسطة رادار ليبور)' : '(Generated by Radar Labour)';
